// Builds src/screens/chapters/circuits.ts: the SCCA chapter's four circuits as
// top-down outlines at true scale, read from the 3D venue models the track
// stills already use (public/tracks-3d/models/<slug>.json, model.circuit:
// OpenStreetMap centreline in metres, x east, z south, north up). Simplified
// (Douglas–Peucker, 2.5 m) and rounded to 0.1 m; the length, layout and its
// source travel with each outline. Run from the repo root:
//   node src/screens/chapters/tools/build-circuits.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';

const TRACKS = {
  'Homestead-Miami Speedway': 'homestead-miami-road-course',
  'Sebring International Raceway': 'sebring-full',
  'Circuit of the Americas': 'circuit-of-the-americas-gp',
  'Michelin Raceway Road Atlanta': 'road-atlanta-full'
};
const TOLERANCE = 2.5;

const simplify = (pts, tol) => {
  const keep = new Uint8Array(pts.length);
  keep[0] = keep[pts.length - 1] = 1;
  const stack = [[0, pts.length - 1]];
  while (stack.length) {
    const [a, b] = stack.pop();
    const [ax, ay] = pts[a];
    const [bx, by] = pts[b];
    const len = Math.hypot(bx - ax, by - ay) || 1;
    let worst = -1;
    let at = -1;
    for (let i = a + 1; i < b; i += 1) {
      const d = Math.abs((bx - ax) * (ay - pts[i][1]) - (ax - pts[i][0]) * (by - ay)) / len;
      if (d > worst) {
        worst = d;
        at = i;
      }
    }
    if (worst > tol) {
      keep[at] = 1;
      stack.push([a, at], [at, b]);
    }
  }
  return pts.filter((_, i) => keep[i]);
};

const out = [];
for (const [trackName, slug] of Object.entries(TRACKS)) {
  const file = `public/tracks-3d/models/${slug}.json`;
  const raw = readFileSync(file);
  const json = JSON.parse(raw);
  const circuit = json.model.circuit;
  const pts = simplify(circuit.pts, TOLERANCE).map(([x, z]) => [Math.round(x * 10) / 10, Math.round(z * 10) / 10]);
  out.push({
    trackName,
    slug,
    layout: json.source.career.layout,
    officialM: circuit.officialM,
    direction: circuit.direction,
    lengthSource: json.source.career.lengthSource.split(' | ')[0],
    model: `${file} (sha256 ${createHash('sha256').update(raw).digest('hex').slice(0, 16)})`,
    pts
  });
}

const body = `/* Generated by tools/build-circuits.mjs: do not edit. The SCCA chapter's four
 * circuits, top-down at true scale (metres, x east, y south, north up), from the
 * 3D venue models' OpenStreetMap centrelines (© OpenStreetMap contributors,
 * ODbL 1.0), simplified to ${TOLERANCE} m. */

export interface Circuit {
  trackName: string;
  slug: string;
  layout: string;
  officialM: number;
  direction: 'clockwise' | 'counterclockwise';
  lengthSource: string;
  model: string;
  pts: Array<[number, number]>;
}

export const CIRCUITS: Circuit[] = ${JSON.stringify(out)};
`;
writeFileSync('src/screens/chapters/circuits.ts', body);
